/** The app screen for a website path (a notification's link, say), or null if it opens on the website. */
export function appRoute(webPath: string | null | undefined): string | null {
  if (!webPath) return null;
  const path = webPath.split('?')[0].split('#')[0];
  return BUILT[path] ?? null;
}
